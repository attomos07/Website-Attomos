  function time(hm, short) {
    var p = String(hm).split(':'), h = +p[0], mi = +p[1];
    if (lang === 'es' || lang === 'en') {
      var h12 = h % 12 || 12, ap = h >= 12 ? 'pm' : 'am';
      if (short) return h12 + (mi ? ':' + p[1] : '') + ' ' + ap;
      return h12 + ':' + p[1] + ' ' + ap.toUpperCase();
    }
    var o = { hour: 'numeric', minute: '2-digit' };
    return fmt(new Date(2026, 0, 1, h, mi), o);
  }
