  function stored() { try { return localStorage.getItem('attomos_lang') || localStorage.getItem('lang'); } catch (_) { return null; } }
  function detect() {
    var s = stored();
    if (s && DICT[s]) return s;
    var nav = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'es']);
    for (var i = 0; i < nav.length; i++) {
      var c = String(nav[i] || '').slice(0, 2).toLowerCase();
      if (DICT[c]) return c;
    }
    return 'es';
  }
