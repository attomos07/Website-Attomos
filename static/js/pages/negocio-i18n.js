  function parseISO(s) { var p = String(s).split('-'); return new Date(+p[0], +p[1] - 1, +p[2]); }
  function fmt(d, opts) { try { return new Intl.DateTimeFormat(loc(), opts).format(d); } catch (_) { return new Intl.DateTimeFormat('en-US', opts).format(d); } }
  // Un domingo de referencia (4 de enero de 2026) para sacar nombres de días.
  function weekdayName(dow, style) { return fmt(new Date(2026, 0, 4 + (+dow)), { weekday: style || 'long' }); }
  function weekdays(style) { var a = []; for (var i = 0; i < 7; i++) a.push(weekdayName(i, style)); return a; }
  function months(style) { var a = []; for (var i = 0; i < 12; i++) a.push(fmt(new Date(2026, i, 1), { month: style || 'long' })); return a; }
  // "martes 24 de noviembre" / "Tuesday, November 24" / "11月24日火曜日"…
  function date(iso) {
    var d = typeof iso === 'string' ? parseISO(iso) : iso;
    if (lang === 'es') return weekdayName(d.getDay()) + ' ' + d.getDate() + ' de ' + months()[d.getMonth()];
    return fmt(d, { weekday: 'long', day: 'numeric', month: 'long' });
  }
